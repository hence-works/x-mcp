#!/usr/bin/env python3
"""Render src/auth/tool-scopes.ts (OAuth 2.0 scopes per tool) from coverage/manifest.json.
Usage: python3 -I scripts/coverage/render_scope_map.py coverage/manifest.json src/auth/tool-scopes.ts
"""
import json
import sys

# Extra (non-Composio) tools: scopes from the X spec security of the operation they call.
EXTRA_SCOPES = {'X_FINALIZE_MEDIA_UPLOAD': ['media.write']}

m = json.load(open(sys.argv[1]))
rows = {}
for t in m['tools']:
    if not all('oauth2_user' in e['auth'] for e in t['endpoints']):
        continue
    scopes = sorted({s for e in t['endpoints'] for s in e['oauth2_scopes']})
    rows[t['name']] = scopes
rows.update(EXTRA_SCOPES)
lines = [
    '// Generated by scripts/coverage/render_scope_map.py from coverage/manifest.json. Do not edit.',
    '',
    '/** OAuth 2.0 scopes each tool needs (X OpenAPI security). Tools absent here cannot use OAuth 2.0 user tokens. */',
    'export const TOOL_OAUTH2_SCOPES: Readonly<Record<string, readonly string[]>> = {',
]
for name in sorted(rows):
    lines.append(f"  {name}: [{', '.join(repr(s).replace(chr(39), chr(39)) for s in rows[name])}],")
lines.append('};')
lines.append('')
open(sys.argv[2], 'w').write('\n'.join(lines))
print(f'{len(rows)} tools')
