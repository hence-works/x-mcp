import { z } from 'zod';
import { invalidInput } from '../x/errors.js';
import { httpTool, type ToolDefinition } from './framework.js';
import { expansions, fields, maxResults, meId, paginationToken, postExpansionFields, userExpansionFields, xId } from './schemas.js';

const USER_CONTEXT = ['oauth2_user', 'oauth1_user'] as const;
const OAUTH2_ONLY = ['oauth2_user'] as const;
const ANY_AUTH = ['oauth2_user', 'oauth1_user', 'app_bearer'] as const;
const scope = 'lists-bookmarks-relationships' as const;

const listId = (what = 'List id') => xId(what);

const listLookupFields = {
  expansions,
  list_fields: fields('List'),
  user_fields: fields('User'),
};

const userPage = (max: number) => ({
  max_results: maxResults(1, max),
  pagination_token: paginationToken,
  ...userExpansionFields,
});

const listPage = {
  max_results: maxResults(1, 100),
  pagination_token: paginationToken,
  ...listLookupFields,
};

